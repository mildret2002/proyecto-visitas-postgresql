BEGIN;

CREATE TABLE departamento (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE rol (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INTEGER NOT NULL REFERENCES rol(id_rol),
    id_departamento INTEGER NOT NULL
        REFERENCES departamento(id_departamento),
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    correo VARCHAR(254) NOT NULL UNIQUE,
    contrasena_hash TEXT NOT NULL
);

CREATE TABLE carrera (
    id_carrera INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departamento INTEGER NOT NULL
        REFERENCES departamento(id_departamento),
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE alumno (
    num_control VARCHAR(20) PRIMARY KEY,
    id_carrera INTEGER NOT NULL REFERENCES carrera(id_carrera),
    nombres VARCHAR(100) NOT NULL,
    apellido_paterno VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100)
);

CREATE TABLE materia (
    id_materia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrera INTEGER NOT NULL REFERENCES carrera(id_carrera),
    nombre VARCHAR(150) NOT NULL,
    semestre SMALLINT NOT NULL CHECK (semestre > 0),
    id_usuario_docente INTEGER REFERENCES usuario(id_usuario)
);

CREATE TABLE grupo (
    id_grupo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_materia INTEGER NOT NULL REFERENCES materia(id_materia),
    id_usuario_docente INTEGER NOT NULL REFERENCES usuario(id_usuario),
    periodo_escolar VARCHAR(50) NOT NULL
);

-- Tabla de enlace: un alumno puede inscribirse en varios grupos.
CREATE TABLE inscripcion (
    num_control VARCHAR(20) NOT NULL REFERENCES alumno(num_control),
    id_grupo INTEGER NOT NULL REFERENCES grupo(id_grupo),
    PRIMARY KEY (num_control, id_grupo)
);

CREATE TABLE empresa (
    id_empresa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    direccion TEXT,
    telefono VARCHAR(30),
    correo VARCHAR(254)
);

CREATE TABLE solicitud (
    id_solicitud INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_visita DATE NOT NULL,
    id_usuario INTEGER NOT NULL REFERENCES usuario(id_usuario),
    id_grupo INTEGER NOT NULL REFERENCES grupo(id_grupo),
    campus VARCHAR(150) NOT NULL,
    fecha_solicitud DATE NOT NULL DEFAULT CURRENT_DATE,
    telefono VARCHAR(30),
    punto_salida_llegada TEXT,
    periodo_escolar VARCHAR(50) NOT NULL,
    departamento VARCHAR(150),
    opcion_empresa_1 VARCHAR(200) NOT NULL,
    opcion_empresa_2 VARCHAR(200),
    domicilio_opcion_1 TEXT,
    telefono_opcion_1 VARCHAR(30),
    correo_opcion_1 VARCHAR(254),
    domicilio_opcion_2 TEXT,
    telefono_opcion_2 VARCHAR(30),
    correo_opcion_2 VARCHAR(254),
    area_objetivo_visita_op1 TEXT,
    area_objetivo_visita_op2 TEXT
);

CREATE TABLE visita (
    id_visita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud INTEGER NOT NULL REFERENCES solicitud(id_solicitud),
    id_empresa INTEGER NOT NULL REFERENCES empresa(id_empresa),
    fecha_visita DATE NOT NULL,
    hora_salida TIME,
    hora_regreso TIME
);

CREATE TABLE unidad (
    id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placas VARCHAR(20) NOT NULL UNIQUE,
    tipo VARCHAR(80) NOT NULL,
    capacidad INTEGER NOT NULL CHECK (capacidad > 0)
);

CREATE TABLE operador (
    id_operador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido_materno VARCHAR(100),
    apellido_paterno VARCHAR(100) NOT NULL,
    licencia VARCHAR(50) NOT NULL UNIQUE,
    telefono VARCHAR(30),
    direccion TEXT
);

CREATE TABLE transporte (
    id_transporte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_visita INTEGER NOT NULL REFERENCES visita(id_visita),
    id_unidad INTEGER NOT NULL REFERENCES unidad(id_unidad),
    id_operador INTEGER NOT NULL REFERENCES operador(id_operador),
    UNIQUE (id_visita, id_unidad)
);

CREATE TABLE comision (
    id_comision INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_visita INTEGER NOT NULL REFERENCES visita(id_visita),
    id_usuario_docente INTEGER NOT NULL REFERENCES usuario(id_usuario),
    folio VARCHAR(50) NOT NULL UNIQUE,
    fecha_emision DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE viaticos (
    id_viatico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comision INTEGER NOT NULL REFERENCES comision(id_comision),
    concepto TEXT NOT NULL,
    monto NUMERIC(12,2) NOT NULL CHECK (monto >= 0)
);

CREATE TABLE reporte (
    id_reporte INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_visita INTEGER NOT NULL REFERENCES visita(id_visita),
    id_usuario_docente INTEGER NOT NULL REFERENCES usuario(id_usuario),
    descripcion TEXT NOT NULL,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    evidencia TEXT
);

CREATE TABLE asistencia (
    id_asistencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_control_alumno VARCHAR(20) NOT NULL
        REFERENCES alumno(num_control),
    id_visita INTEGER NOT NULL REFERENCES visita(id_visita),
    asistencia BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (num_control_alumno, id_visita)
);

COMMIT;